// 三语字典与语言路由助手。
//
// 语言闭集必须与后台「店铺设置」里的 locales 一致（zh-CN / zh-HK / en），
// 不能自造 zh-Hant / zh-Hant-HK 之类的变体：storefront 接口按同一组值校验，
// 多传一个值就是 422。html lang 与 hreflang 才用完整的 BCP 47 写法。
//
// 文案集中在这里而不是散落在组件中：一是三语必须逐字对照，二是缺译在
// TypeScript 里就是编译错误（Copy 由繁體版本推出来，另外两份必须结构相同）。

export const LOCALES = ['zh-HK', 'zh-CN', 'en'] as const;
export type Locale = (typeof LOCALES)[number];
/** 进站默认语言：站点面向香港，繁體为品牌原始文案。 */
export const DEFAULT_LOCALE: Locale = 'zh-HK';

export const LOCALE_LABEL: Record<Locale, string> = { 'zh-HK': '繁體', 'zh-CN': '简体', en: 'English' };
export const LOCALE_SHORT: Record<Locale, string> = { 'zh-HK': '繁', 'zh-CN': '简', en: 'EN' };
/** html lang：给读屏与搜索引擎的完整 BCP 47 标记。 */
export const HTML_LANG: Record<Locale, string> = { 'zh-HK': 'zh-Hant-HK', 'zh-CN': 'zh-Hans-CN', en: 'en' };
export const OG_LOCALE: Record<Locale, string> = { 'zh-HK': 'zh_HK', 'zh-CN': 'zh_CN', en: 'en_US' };
/** Intl 用的标记（日期/数字格式化）。 */
export const INTL_LOCALE: Record<Locale, string> = { 'zh-HK': 'zh-HK', 'zh-CN': 'zh-CN', en: 'en-HK' };

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value);
}

/** 路由参数不可信：不认识的段一律按默认语言处理，交给上层决定是否 404。 */
export function resolveLocale(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

/** 站内绝对路径（不含域名）：localePath('en', '/products') -> '/en/products'。 */
export function localePath(locale: Locale, path = ''): string {
  if (!path || path === '/') return `/${locale}`;
  return `/${locale}${path.startsWith('/') ? path : `/${path}`}`;
}

/** 用命名占位符填充文案：fill('小計（{count} 件）', { count: 2 })。 */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    (key in values ? String(values[key]) : match));
}

/** canonical/hreflang 用：同一路径在三种语言下的地址。 */
export function altPaths(path = ''): Record<string, string> {
  return {
    'zh-HK': localePath('zh-HK', path),
    'zh-CN': localePath('zh-CN', path),
    en: localePath('en', path),
    'x-default': localePath(DEFAULT_LOCALE, path),
  };
}

